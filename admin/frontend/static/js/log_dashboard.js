    // Thrown by requestJson for any non-2xx *HTTP response* (as opposed to a
    // genuine network failure, which throws whatever plain error fetch()
    // itself rejects with) - lets callers like the session poller tell the
    // two apart (a 404 no_session should not be retried; a dropped
    // connection should).
    class HttpError extends Error {
        constructor(status, body) {
            super(getErrorMessage(status, body));
            this.status = status;
            this.body = body;
            this.code = body && typeof body.error === 'string' ? body.error : null;
        }
    }

    const requestJson = async (url, options) => {
        const response = await fetch(url, options);
        let body = null;
        try {
            body = await response.json();
        } catch (e) {
            body = null;
        }
        if (!response.ok) {
            throw new HttpError(response.status, body);
        }
        return body;
    };

    const buildContentUrl = (localPath, { download = false, maxBytes = null } = {}) => {
        const encoded = String(localPath)
            .split('/')
            .filter((segment) => segment.length > 0)
            .map(encodeURIComponent)
            .join('/');
        const params = new URLSearchParams();
        if (download) params.set('download', '1');
        if (maxBytes) params.set('max_bytes', String(maxBytes));
        const query = params.toString();
        return `${API_BASE}/content/${encoded}${query ? `?${query}` : ''}`;
    };

    // Always requests only the last MAX_VIEW_BYTES — the point is to never pull
    // a full (up to 50MB) log into the DOM just to view it. Full content is
    // still one click away via the download button (buildContentUrl with
    // download=1, unchanged/streamed by the server).
    const fetchLogText = async (localPath) => {
        const response = await fetch(buildContentUrl(localPath, { maxBytes: MAX_VIEW_BYTES }));
        if (!response.ok) {
            let body = null;
            try {
                body = await response.json();
            } catch (e) {
                body = null;
            }
            throw new HttpError(response.status, body);
        }
        const text = await response.text();
        const totalSizeHeader = response.headers.get('X-Log-Size');
        const totalSize = totalSizeHeader !== null ? Number(totalSizeHeader) : null;
        return {
            text,
            truncated: response.headers.get('X-Log-Truncated') === '1',
            totalSize: Number.isFinite(totalSize) ? totalSize : null,
        };
    };


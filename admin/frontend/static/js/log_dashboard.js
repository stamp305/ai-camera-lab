// static/js/log_dashboard.js
//
// Flow: pick an online branch -> the browser starts a background "pull all
// logs" job for it under a session id IT generates -> polls the session's
// status until the job lands on a terminal state -> browse the (already
// progressively-rendered) files in a tree (grouped into folders by log name
// via LogGrouping, see static/js/log_grouping.js, loaded before this file)
// -> click an "ok" file to view it. The session is deleted (which also
// cancels a still-running job) when the admin picks a different branch,
// clicks "เลิกดู / ลบ", or leaves the page.
//
// Only these endpoints are used (all under /ai-camera/api/logs):
//   GET    /branches
//   POST   /branches/<client_id>/pull-all      {session_id}         -> 202 {session_id, client_id, state:"running"}
//   GET    /sessions/<session_id>                                   -> current job status + files (see pollSessionOnce)
//   POST   /branches/<client_id>/pull          {session_id, root, path}  (single-file refresh)
//   DELETE /sessions/<session_id>                                       (normal cleanup; also cancels a running job)
//   POST   /sessions/<session_id>/delete                                (sendBeacon on pagehide; same as DELETE)
//   GET    /content/<local_path>[?max_bytes=N|download=1]
//        Viewer always sends max_bytes=2097152 (2 MiB); when the server
//        truncates (X-Log-Truncated: 1) we only got the last max_bytes of the
//        file (X-Log-Size has the true total). download=1 ignores max_bytes
//        and streams the full file — unrelated to the truncation notice.
//        local_path starts with the session id; we treat it as an opaque
//        '/'-separated string, never parse it.
//
// session_id is always generated by the browser (32 lowercase-hex chars via
// crypto.getRandomValues, see generateSessionId) and sent on every pull-all -
// the server never invents one. state.sessionId is set BEFORE the pull-all
// POST goes out (not after it resolves), so pagehide's sendBeacon cleanup and
// "switch branch mid-pull" both work even while that very first request is
// still in flight. Every async continuation below (the pull-all POST, every
// poll) re-checks its own session id against state.sessionId before touching
// state/DOM, so a superseded request (old branch, or a stale "ดึงใหม่" click)
// can never clobber whatever the admin has since moved on to.

